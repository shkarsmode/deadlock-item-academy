export type IconName = keyof typeof ICONS;

const cache = new Map<string, string>();
function svgFor(name: IconName, size: number, stroke: number): string {
  const key = `${name}:${size}:${stroke}`;
  const hit = cache.get(key);
  if (hit) return hit;
  const body = (ICONS[name] as IconNode)
    .map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).map(([k, v]) => `${k}="${String(v)}"`).join(' ')}/>`)
    .join('');
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true" focusable="false">${body}</svg>`;
  cache.set(key, svg);
  return svg;
}

/** Inline SVG icon from the Lucide set (static, trusted markup). */
@Component({
  selector: 'app-icon',
  changeDetection: ChangeDetectionStrategy.OnPush,
  template: '',
  host: { '[innerHTML]': 'html()', class: 'ui-icon', '[style.width.px]': 'size()', '[style.height.px]': 'size()' },
  styles: [':host{display:inline-flex;flex:none;line-height:0}'],
})
export class Icon {
  private readonly sanitizer = inject(DomSanitizer);
  readonly name = input.required<IconName>();
  readonly size = input(18);
  readonly stroke = input(1.9);
  protected readonly html = computed<SafeHtml>(() => this.sanitizer.bypassSecurityTrustHtml(svgFor(this.name(), this.size(), this.stroke())));
}
